export function translate(
  lang: LangCode,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const entry = MESSAGES[key];
  if (!entry) return key;
  let text = entry[lang] ?? entry.en ?? entry.vi ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

